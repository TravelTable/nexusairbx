const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const { CURRENT_STUDIO_PLUGIN_RELEASE } = require('../backend/src/lib/studioPluginReleases');
execFileSync(process.execPath, [path.join(root, 'roblox-plugin/build/verify-plugin-artifact.js')], { stdio: 'inherit' });
const source = path.join(root, 'roblox-plugin/build/NexusRBXStudioBridge.rbxmx');
const bytes = fs.readFileSync(source);
if (!bytes.includes(Buffer.from(CURRENT_STUDIO_PLUGIN_RELEASE.buildId))) throw new Error('Local plugin artifact does not match the backend release.');
const publicDownload = path.join(root, 'public/studio-plugin/NexusRBXStudioBridge.rbxmx');
fs.rmSync(publicDownload, { force: true });
console.log('Local plugin artifact matches the backend release. The public site does not publish it.');
