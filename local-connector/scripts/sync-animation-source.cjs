// Share the actual plugin implementation with the standalone connector. No
// runtime backend dependency or user-supplied executable code is introduced.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../..");
const sources = ["animation.lua", "animationInspection.lua"].map(name =>
  fs.readFileSync(path.join(root, "roblox-plugin/src/commands", name), "utf8").replace(/\r\n/g, "\n"));
const output = "// Generated by scripts/sync-animation-source.cjs; edit the plugin sources.\n"
  + "export const ANIMATION_STUDIO_SOURCE = " + JSON.stringify(sources.join("\n")) + ";\n";
const target = path.join(root, "local-connector/src/animation-studio-source.ts");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) throw new Error("Connector animation source is stale; run npm run sync:animation in local-connector");
} else fs.writeFileSync(target, output);
